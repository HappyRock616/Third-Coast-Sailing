// Generate manifest.xml (product list) and monkey.jungle (per-device source and annotation choices) from the
// device survey, using the tiers in docs/COMPATIBILITY.md. Re-run after changing tiers or installing devices.
// Usage: node tools/gen_build.js
const fs = require("fs");
const path = require("path");
const { execFileSync } = require("child_process");
const root = path.join(__dirname, "..");
const rows = JSON.parse(execFileSync(process.execPath, [path.join(__dirname, "device_survey.js")], { maxBuffer: 1 << 24 }).toString());
const ver = s => s.split(".").map(Number).reduce((a, b, i) => a + b * [1e6, 1e3, 1][i], 0);
const MIN_API = "3.2.0";
function tier(x) {
  if (!x.memKB || ver(x.ciqMax) < ver(MIN_API) || x.memKB < 96) return "X";
  if (x.bpp == 1) return "M";
  if (x.memKB <= 128) return "L";
  if (/edge|gpsmap|montana|oregon|rino|etrex/.test(x.id)) return "N";
  if (x.shape === "rectangle") return "R";
  return "F";
}
// Dropped 2026-11-24 (HappyRock: a model that looks cluttered or doesn't work is not built): N = bike computers and
// handhelds (the round layout fills a third of the screen, text too small), R = rectangular watches (Venu Sq: text
// overflows boxes and panels), M = monochrome Instinct / Descent G1 (the sub-screen window cuts the Next mark box and
// the phone icon, and the release build peaks at 88 of 94 KB). They can come back with their own layouts.
const DROPPED = ["X", "N", "R", "M"];
const keep = rows.filter(r => !DROPPED.includes(tier(r)));
// Devices without Toybox.BluetoothLowEnergy (no direct phone link): filled in from the compile check
const NO_BLE = [];
// The direct Bluetooth link (Ble.mc, PROTOCOL 8) is off: the phone link goes through Gadgetbridge (PROTOCOL 9). While
// false, every build compiles Ble.mc out (its stub stays) and the manifest asks for no Bluetooth permission.
const DIRECT_BLE = false;
const APP_ID = "5c1e7a2b9d4f4e0a8b3c6d1f2e7a9b40";
const manifest = `<?xml version="1.0"?>
<!-- Generated by tools/gen_build.js from the SDK device survey. Edit the tiers there, not here. -->
<iq:manifest version="3" xmlns:iq="http://www.garmin.com/xml/connectiq">
    <iq:application id="${APP_ID}" type="watch-app" name="@Strings.AppName" entry="TcsApp" launcherIcon="@Drawables.LauncherIcon" minApiLevel="${MIN_API}">
        <iq:products>
${keep.map(r => `            <iq:product id="${r.id}"/>`).join("\n")}
        </iq:products>
        <iq:permissions>
${DIRECT_BLE ? `            <iq:uses-permission id="BluetoothLowEnergy"/>
` : ""}            <iq:uses-permission id="Communications"/>
            <iq:uses-permission id="Positioning"/>
            <iq:uses-permission id="Sensor"/>
        </iq:permissions>
        <iq:languages>
            <iq:language>eng</iq:language>
        </iq:languages>
        <iq:barrels/>
    </iq:application>
</iq:manifest>
`;
// Annotations compiled out per tier:  sight = Sight page and its views (not on Lite / Mono);
// full / lite pick the buffer sizes in Limits.mc.
const lines = [
  "# Generated by tools/gen_build.js. Tiers: docs/COMPATIBILITY.md",
  "project.manifest = manifest.xml",
  "",
  "base.sourcePath = source;source-color",
  `base.excludeAnnotations = lite;tour;${DIRECT_BLE ? "noble" : "ble"};log`,
  "",
];
for (const r of keep) {
  const t = tier(r);
  const ble = (!DIRECT_BLE || NO_BLE.includes(r.id)) ? "ble" : "noble";      // which Bluetooth variant to compile out
  if (t === "M") lines.push(`${r.id}.sourcePath = source;source-mono`, `${r.id}.excludeAnnotations = full;sight;tour;${ble};log`);
  else if (t === "L") lines.push(`${r.id}.excludeAnnotations = full;sight;tour;${ble};log`);
  else if (ble === "ble" && DIRECT_BLE) lines.push(`${r.id}.excludeAnnotations = lite;tour;ble;log`);
}
fs.writeFileSync(path.join(root, "manifest.xml"), manifest);
fs.writeFileSync(path.join(root, "monkey.jungle"), lines.join("\n") + "\n");
// test.jungle: the same, but with the demo tour compiled in (:tour) and its stub out (:notour). For debug builds
// in the simulator only (scripts/sim.sh --tour); release builds always use monkey.jungle.
const test = lines.map(l => l.startsWith("#")
  ? "# Generated by tools/gen_build.js. Demo tour build for simulator screenshots (scripts/sim.sh --tour)"
  : l.replace(/;tour(;|$)/, ";notour$1"));
fs.writeFileSync(path.join(root, "test.jungle"), test.join("\n") + "\n");
// linktest.jungle: a release-style build with the link log compiled in (:log) and its stub out (:nolog), for the
// real-watch link test (scripts/linktest.ps1). Never for the store.
const linktest = lines.map(l => l.startsWith("#")
  ? "# Generated by tools/gen_build.js. Link test build with logging (scripts/linktest.ps1); never for the store"
  : l.replace(/;log$/, ";nolog"));
fs.writeFileSync(path.join(root, "linktest.jungle"), linktest.join("\n") + "\n");
const count = {}; keep.forEach(r => { const t = tier(r); count[t] = (count[t] || 0) + 1; });
console.log("products:", keep.length, JSON.stringify(count));
